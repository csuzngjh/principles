// SPEC-PD-EXAMINER-001 v0.7 §4 — experiment isolation contracts.
//
// Three designs are DEFINED here; only the verification contract is
// implemented. The 2×2 factorial EXECUTION system is explicitly out of scope
// this round (SPEC §10 Phase 3): its effect formulas live in
// challenge-statistics.mjs#computeFactorialEffect.
//
// P1-1 (PR #2239 review) rebuilds verification around ACTUAL LOAD EVIDENCE:
// a configuration DECLARATION is never proof of what a run actually loaded.
// Every runtime-shaping variable is tracked in three states —
//   DECLARED — the arm config claims a value
//   LOADED   — runner-collected load evidence carries an observed value
//   VERIFIED — the loaded value matches the frozen expectation AND the
//              cross-arm isolation constraints
// DECLARED never auto-upgrades to VERIFIED. Load evidence is generated by the
// RUNNER (collectOfflineStubLoadEvidence below — the only producer for the
// offline scope; a trusted host probe would be the real-host producer) and is
// tamper-evident via a canonical evidence hash the verifier recomputes. An
// actor-supplied or hand-edited evidence object fails the hash/provenance
// check and the gate refuses BEFORE any execution action exists.
//
// Offline honesty rule: variables an offline-stub run CANNOT observe (real
// model identity, host hooks, live memory, wall-clock sessions) stay UNKNOWN
// — the verdict is ISOLATION_VERIFIED_OFFLINE_SCOPE, never a fabricated
// full ISOLATION_VERIFIED. Real-host studies (mode 'real-host') require those
// variables VERIFIED from trusted probe evidence or the gate returns
// EXPERIMENT_BLOCKED — fail-closed, no execution.
//
// Zero network, zero clock, zero side effects.

import { hashOfCanonical } from './challenge-freeze.mjs';

export const ISOLATION_FROZEN_VARIABLES = [
  'model', 'host', 'memory', 'hook', 'tools', 'initialState', 'budget',
  'provider', 'systemPrompt', 'plugin', 'commonContext',
];

// Variables whose ACTUAL load state an offline deterministic run can prove
// from its own controlled materials; everything else needs a host probe.
export const OFFLINE_PROVABLE_VARIABLES = ['principle', 'ruleCode', 'commonContext'];
// Host-shaped variables: offline runs can never honestly observe these.
export const HOST_PROBE_VARIABLES = [
  'model', 'systemPrompt', 'provider', 'plugin', 'tools', 'memory', 'hook',
  'session', 'workspace',
];

export const LOAD_EVIDENCE_STATES = ['DECLARED', 'LOADED', 'VERIFIED'];

export const EXPERIMENT_DESIGNS = {
  principleOnly: {
    designId: 'principle-only-ab',
    purpose: 'measure the natural-language Principle\'s behavior increment with NO target RuleCode execution constraint',
    reference: 'SPEC v0.7 §4.2',
    arms: {
      control: { targetPrinciple: 'OFF', targetRuleCode: 'OFF' },
      treatment: { targetPrinciple: 'ON', targetRuleCode: 'OFF' },
    },
    rule: 'the ONLY treatment variable is the injection of the target Principle',
  },
  ruleCodeOnly: {
    designId: 'rulecode-only-ab',
    purpose: 'measure the machine-executed RuleCode\'s behavior effect with the Principle absent',
    reference: 'SPEC v0.7 §4.3',
    arms: {
      control: { targetPrinciple: 'OFF', targetRuleCode: 'OFF' },
      treatment: { targetPrinciple: 'OFF', targetRuleCode: 'ON' },
    },
    rule: 'separate engineering/behavior research — not required this round and not authorized by any current grant',
  },
  factorial2x2: {
    designId: 'factorial-2x2',
    purpose: 'separate Principle main effect, RuleCode main effect and their interaction',
    reference: 'SPEC v0.7 §4.4',
    arms: {
      P0R0: { targetPrinciple: 'OFF', targetRuleCode: 'OFF' },
      P1R0: { targetPrinciple: 'ON', targetRuleCode: 'OFF' },
      P0R1: { targetPrinciple: 'OFF', targetRuleCode: 'ON' },
      P1R1: { targetPrinciple: 'ON', targetRuleCode: 'ON' },
    },
    effects: 'computeFactorialEffect in challenge-statistics.mjs (Δ_P^R0, Δ_P^R1, interaction I)',
    rule: 'computation contract only — the 2×2 execution system is out of scope this round',
  },
};

const JUDGE_SIDE_LEAK_KEYS = [
  'goldTruth', 'implies', 'acceptableVerdicts', 'supportRules', 'expectedMode',
  'ownerAnswers', 'principlePredicates', 'costEnvelope', 'pathConstraints',
];

function text(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

/**
 * RUNNER-controlled producer of offline-stub actual load evidence — the only
 * legitimate producer for the offline scope. Actors never get to construct or
 * mutate this object. Values are taken from freshly recomputed frozen
 * materials (never cached config), and everything an offline run cannot
 * observe stays explicit null (UNKNOWN), never a fabricated default.
 *
 * @param {object} input.frozen — verifyFrozenStudy output (studyId, suite/mapping/grader/principle hashes)
 * @param {object} input.armCheck — verifyArmConfigsFrozen output ({ arms, commonContextHash })
 * @param {Record<string, string>} input.armBindings — design-arm → arm-config key
 *   (e.g. { control: 'A', treatment: 'B' }) so the evidence is keyed by the
 *   DESIGN arm identity the verifier reasons about.
 * @param {object} input.executionOrder — the ACTUAL dispatch order as executed
 *   ({ strategy: 'randomized'|'balanced', seed, order: ['caseId/armId/rrep', ...] })
 */
export function collectOfflineStubLoadEvidence({ frozen, armCheck, armBindings, executionOrder }) {
  if (!frozen || !frozen.studyId) throw new Error('collectOfflineStubLoadEvidence: frozen (verifyFrozenStudy output) required');
  if (!armCheck || !armCheck.arms) throw new Error('collectOfflineStubLoadEvidence: armCheck (verifyArmConfigsFrozen output) required');
  if (!armBindings || typeof armBindings !== 'object' || Object.keys(armBindings).length === 0) throw new Error('collectOfflineStubLoadEvidence: armBindings (design-arm → arm-config key) required');
  if (!executionOrder || !['randomized', 'balanced'].includes(executionOrder.strategy) || !Array.isArray(executionOrder.order) || !text(executionOrder.seed)) {
    throw new Error('collectOfflineStubLoadEvidence: executionOrder { strategy: randomized|balanced, seed, order[] } required — the record of what ACTUALLY ran, not an intention');
  }
  const arms = {};
  for (const [designArm, configKey] of Object.entries(armBindings)) {
    const arm = armCheck.arms[configKey];
    if (!arm) throw new Error(`collectOfflineStubLoadEvidence: armBindings.${designArm} → '${configKey}' not present in the arm configs`);
    const payloadEmpty = arm.delivery.payloadText === '';
    arms[designArm] = {
      // The delivery the run actually carries: the arm's recomputed payload
      // hash (null-payload = the empty control arm — Principle NOT loaded).
      resolvedPrincipleHash: payloadEmpty ? null : arm.delivery.payloadHash,
      resolvedPrincipleLoaded: !payloadEmpty,
      // Offline deterministic environment: no RuleCode execution channel
      // exists at all, so the load state is a structural fact, not a claim.
      actualRuleCodeState: 'OFF',
      actualRuleCodeStateBasis: 'OFF_BY_ABSENCE_OF_MECHANISM',
      // Provable offline: the shared common context hash, recomputed.
      commonContextHash: armCheck.commonContextHash,
      // Host-shaped facts an offline run cannot observe — explicit UNKNOWN.
      modelIdentity: null,
      systemPromptHash: null,
      providerIdentity: null,
      pluginSetHash: null,
      toolsSetHash: null,
      memoryIdentity: null,
      hookSetHash: null,
      sessionIdentity: null,
      workspaceIdentity: null,
    };
  }
  const core = {
    generatedBy: 'runner-offline-stub',
    studyId: frozen.studyId,
    suiteHash: frozen.suiteHash,
    mappingHash: frozen.mappingHash,
    graderHash: frozen.graderHash,
    executionMode: 'offline-stub',
    arms,
    randomizationRecord: {
      strategy: executionOrder.strategy,
      seed: executionOrder.seed,
      actualOrder: executionOrder.order.slice(),
    },
  };
  return { ...core, evidenceHash: hashOfCanonical(core) };
}

function verifyEvidenceIntegrity(actualLoad, problems, check) {
  if (!actualLoad || typeof actualLoad !== 'object') {
    check('load_evidence_present', false, 'no actual load evidence supplied — declarations alone can never authorize execution');
    return null;
  }
  if (!['runner-offline-stub', 'trusted-host-probe'].includes(actualLoad.generatedBy)) {
    check('load_evidence_provenance', false, `load evidence generatedBy '${String(actualLoad.generatedBy)}' is not a trusted producer (runner-offline-stub | trusted-host-probe) — actor-supplied evidence is refused`);
    return null;
  }
  const { evidenceHash, ...core } = actualLoad;
  if (!/^[a-f0-9]{64}$/.test(String(evidenceHash || '')) || hashOfCanonical(core) !== evidenceHash) {
    check('load_evidence_hash', false, 'load evidence hash mismatch — the evidence object was modified after generation (or forged)');
    return null;
  }
  return actualLoad;
}

/**
 * Fail-closed verification of a declared experiment against its design.
 * PURE function: no execution action, no reservation, no actor construction.
 *
 * @param {string} input.design — one of EXPERIMENT_DESIGNS
 * @param {Record<string, object>} input.arms — declared arm conditions
 * @param {object} input.actualLoad — runner-produced load evidence
 *   (collectOfflineStubLoadEvidence, or a trusted host probe in real mode)
 * @param {object} input.expectations — frozen expectations the LOADED values
 *   must re-bind to: { principleHash, commonContextHash, modelIdentity,
 *   systemPromptHash, providerIdentity, pluginSetHash, toolsSetHash,
 *   memoryIdentity, hookSetHash } (offline scope supplies principleHash +
 *   commonContextHash; host-shaped expectations come from the frozen plan)
 * @param {object} input.execution — { orderStrategy, orderRecord, repetitionsPlanned, preregistrationRef }
 * @param {'offline-stub'|'real-host'} input.mode — offline scope tolerates
 *   host-probe variables staying UNKNOWN (verdict is scoped, never full
 *   ISOLATION_VERIFIED); real-host mode requires them VERIFIED or BLOCKED.
 * @param {object} [input.actorInputs] — optional serialized actor-visible
 *   inputs per arm for judge-side leak checks.
 */
export function verifyIsolationContract({ design, arms, actualLoad, expectations, execution, mode = 'offline-stub', actorInputs }) {
  const problems = [];
  const checks = [];
  const check = (id, ok, detail) => {
    checks.push({ id, ok, detail });
    if (!ok) problems.push(detail);
  };
  if (!Object.hasOwn(EXPERIMENT_DESIGNS, design)) throw new Error(`verifyIsolationContract: unknown design '${String(design)}'`);
  if (!['offline-stub', 'real-host'].includes(mode)) throw new Error(`verifyIsolationContract: mode must be 'offline-stub'|'real-host' (got '${String(mode)}')`);
  if (!arms || typeof arms !== 'object' || Array.isArray(arms)) throw new Error('verifyIsolationContract: arms object required');
  if (!expectations || typeof expectations !== 'object') throw new Error('verifyIsolationContract: expectations object required (frozen hashes the loaded values must re-bind to)');
  if (!execution || typeof execution !== 'object') throw new Error('verifyIsolationContract: execution object required');
  const spec = EXPERIMENT_DESIGNS[design];
  const armIds = Object.keys(spec.arms);
  for (const armId of armIds) {
    if (!arms[armId] || typeof arms[armId] !== 'object') throw new Error(`verifyIsolationContract: arms.${armId} required for design ${spec.designId}`);
  }
  for (const armId of Object.keys(arms)) {
    if (!armIds.includes(armId)) check('arm_out_of_design', false, `arm '${armId}' does not belong to design ${spec.designId}`);
  }

  // 1. treatment-variable matrix must match the design exactly
  for (const armId of armIds) {
    for (const variable of ['targetPrinciple', 'targetRuleCode']) {
      const declared = arms[armId][variable];
      const expected = spec.arms[armId][variable];
      check(`matrix_${armId}_${variable}`, declared === expected, `arm ${armId}: ${variable} must be ${expected} (declared ${String(declared)})`);
    }
  }

  // 2. every frozen variable identical across arms (the declared plane)
  for (const variable of ISOLATION_FROZEN_VARIABLES) {
    const values = armIds.map((armId) => arms[armId][variable]);
    if (values.some((value) => value === undefined)) {
      check(`frozen_${variable}_declared`, false, `frozen variable '${variable}' missing on at least one arm — an undeclared confound cannot be verified`);
      continue;
    }
    const identical = values.every((value) => JSON.stringify(value) === JSON.stringify(values[0]));
    check(`frozen_${variable}_identical`, identical, `frozen variable '${variable}' differs across arms (${armIds.map((armId, i) => `${armId}=${JSON.stringify(values[i])}`).join(', ')})`);
  }

  // 3. load-evidence integrity (provenance + tamper-evidence) — refusal here
  //    is fail-closed for every later step.
  const load = verifyEvidenceIntegrity(actualLoad, problems, check);
  const perArmLoad = load && load.arms ? load.arms : {};
  const state = { perArm: {} };
  const classify = (loaded, matches) => (loaded === undefined || loaded === null ? 'DECLARED' : matches ? 'VERIFIED' : 'LOADED');

  // 4. Principle actual-load: the treatment variable itself must be LOADED
  //    exactly per design — ON arms carry the frozen principle hash, OFF
  //    arms carry NO principle payload at all.
  for (const armId of armIds) {
    const expectedOn = spec.arms[armId].targetPrinciple === 'ON';
    const armLoad = perArmLoad[armId];
    if (!armLoad) {
      check(`load_arm_present_${armId}`, false, `no load evidence for arm ${armId} — its actual state is unknown, execution is refused`);
      state.perArm[armId] = { principle: 'DECLARED', ruleCode: 'DECLARED' };
      continue;
    }
    const loadedHash = armLoad.resolvedPrincipleHash;
    if (expectedOn) {
      const matches = text(loadedHash) && text(expectations.principleHash) && loadedHash === expectations.principleHash;
      state.perArm[armId] = { principle: classify(loadedHash, matches) };
      check(`load_principle_${armId}`, matches,
        `arm ${armId} declares the Principle ON but the loaded payload ${loadedHash === null ? 'is absent' : `'${String(loadedHash).slice(0, 12)}…' does not re-bind to the frozen principle hash`} — the treatment was not verifiably injected`);
    } else {
      const clean = loadedHash === null && armLoad.resolvedPrincipleLoaded !== true;
      state.perArm[armId] = { principle: clean ? 'VERIFIED' : 'LOADED' };
      check(`load_principle_absent_${armId}`, clean,
        `arm ${armId} declares the Principle OFF but carries a loaded principle payload ('${String(loadedHash).slice(0, 12)}…') — Principle leak into the control arm`);
    }
  }

  // 5. RuleCode actual-load state must equal the design matrix
  for (const armId of armIds) {
    const armLoad = perArmLoad[armId];
    const expected = spec.arms[armId].targetRuleCode;
    const actual = armLoad ? armLoad.actualRuleCodeState : undefined;
    const matches = actual === expected;
    if (state.perArm[armId]) state.perArm[armId].ruleCode = classify(actual, matches);
    check(`load_rulecode_${armId}`, matches,
      `arm ${armId}: declared RuleCode ${expected} but the actually loaded state is '${String(actual)}' — a confounded treatment variable refuses execution`);
  }

  // 6. common context: recomputed hash must re-bind to the frozen expectation
  //    and stay identical across arms (shared BY DESIGN — drift or divergence
  //    from the frozen value is the failure, never the sharing itself).
  for (const armId of armIds) {
    const armLoad = perArmLoad[armId];
    const loaded = armLoad ? armLoad.commonContextHash : undefined;
    const matches = text(loaded) && text(expectations.commonContextHash) && loaded === expectations.commonContextHash;
    if (state.perArm[armId]) state.perArm[armId].commonContext = classify(loaded, matches);
    check(`load_common_context_${armId}`, matches,
      `arm ${armId}: loaded commonContextHash ${loaded === undefined || loaded === null ? 'missing' : `'${String(loaded).slice(0, 12)}…'`} does not re-bind to the frozen common context — the shared context drifted from the preregistered plan`);
  }

  // 7. host-probe variables: declared-identical (step 2) plus either VERIFIED
  //    against the frozen expectation or explicitly UNKNOWN (offline scope).
  //    session/workspace have NO shared expectation by design (they must be
  //    per-arm distinct) — they are checked for existence and cross-arm
  //    uniqueness only.
  for (const variable of HOST_PROBE_VARIABLES) {
    const key = {
      model: 'modelIdentity', systemPrompt: 'systemPromptHash', provider: 'providerIdentity',
      plugin: 'pluginSetHash', tools: 'toolsSetHash', memory: 'memoryIdentity', hook: 'hookSetHash',
      session: 'sessionIdentity', workspace: 'workspaceIdentity',
    }[variable];
    const perArmDistinct = variable === 'session' || variable === 'workspace';
    for (const armId of armIds) {
      const armLoad = perArmLoad[armId];
      const loaded = armLoad ? armLoad[key] : undefined;
      if (loaded === null || loaded === undefined) {
        if (mode === 'real-host') {
          check(`load_${variable}_${armId}`, false, `real-host study: '${variable}' has no actual load evidence — trusted host-probe proof is required and its absence BLOCKS execution`);
        }
        if (state.perArm[armId]) state.perArm[armId][variable] = 'UNKNOWN';
        continue;
      }
      if (perArmDistinct) {
        if (state.perArm[armId]) state.perArm[armId][variable] = 'LOADED'; // uniqueness decided below
        continue;
      }
      // Model identity additionally has to re-bind to the declared value.
      const expectation = expectations[key];
      let matches = text(expectation) && loaded === expectation;
      if (variable === 'model' && matches) {
        matches = String(loaded).includes(String(arms[armId].model));
      }
      if (state.perArm[armId]) state.perArm[armId][variable] = classify(loaded, matches);
      check(`load_${variable}_${armId}`, matches,
        `arm ${armId}: loaded ${key} '${String(loaded).slice(0, 40)}' does not match the frozen expectation${variable === 'model' ? ` (declared model '${String(arms[armId].model)}')` : ''} — runtime drift refuses execution`);
    }
  }
  // session/workspace: distinct across arms whenever they ARE observed
  for (const variable of ['sessionIdentity', 'workspaceIdentity']) {
    const seen = new Map();
    for (const armId of armIds) {
      const armLoad = perArmLoad[armId];
      const loaded = armLoad ? armLoad[variable] : null;
      if (!text(loaded)) continue;
      if (seen.has(loaded)) {
        check(`${variable}_shared`, false, `${variable} '${loaded}' shared by arms ${seen.get(loaded)} and ${armId} — cross-arm contamination`);
      } else {
        seen.set(loaded, armId);
        const stateKey = variable === 'sessionIdentity' ? 'session' : 'workspace';
        if (state.perArm[armId]) state.perArm[armId][stateKey] = 'VERIFIED';
      }
    }
  }
  // declared session/workspace ids (when load evidence is absent) stay distinct too
  const declaredSession = new Map();
  const declaredWorkspace = new Map();
  for (const armId of armIds) {
    if (text(arms[armId].sessionId)) {
      if (declaredSession.has(arms[armId].sessionId)) check('session_declared_shared', false, `sessionId '${arms[armId].sessionId}' shared by arms ${declaredSession.get(arms[armId].sessionId)} and ${armId}`);
      declaredSession.set(arms[armId].sessionId, armId);
    }
    if (text(arms[armId].workspaceId)) {
      if (declaredWorkspace.has(arms[armId].workspaceId)) check('workspace_declared_shared', false, `workspaceId '${arms[armId].workspaceId}' shared by arms ${declaredWorkspace.get(arms[armId].workspaceId)} and ${armId}`);
      declaredWorkspace.set(arms[armId].workspaceId, armId);
    }
  }

  // 8. Principle leak through actor inputs (judge-side keys) when supplied
  if (actorInputs) {
    for (const armId of armIds) {
      const serialized = actorInputs[armId];
      if (typeof serialized !== 'string') {
        check(`actor_input_present_${armId}`, false, `no actor-visible input recorded for arm ${armId} — the leak check cannot run, so the gate fails closed`);
        continue;
      }
      for (const key of JUDGE_SIDE_LEAK_KEYS) {
        if (serialized.includes(`"${key}"`)) check(`gold_leak_${armId}`, false, `actor input of arm ${armId} leaks judge-side key '${key}'`);
      }
    }
  }

  // 9. randomization: an ACTUAL order record, not a declared intention
  const orderStrategy = execution.orderStrategy;
  check('execution_order_strategy', orderStrategy === 'randomized' || orderStrategy === 'balanced', `execution.orderStrategy must be 'randomized' or 'balanced' (got ${String(orderStrategy)})`);
  const record = load ? load.randomizationRecord : null;
  const orderRecordOk = record && ['randomized', 'balanced'].includes(record.strategy) && Array.isArray(record.actualOrder) && record.actualOrder.length > 0 && text(record.seed);
  check('execution_order_record', Boolean(orderRecordOk),
    orderRecordOk ? '' : 'randomization has no actual execution record (strategy+seed+executed order) — a declared intention is not randomization evidence');
  if (orderRecordOk && orderStrategy && record.strategy !== orderStrategy) {
    check('execution_order_consistent', false, `declared orderStrategy '${orderStrategy}' differs from the recorded strategy '${record.strategy}'`);
  }
  const reps = execution.repetitionsPlanned;
  check('repetitions_preregistered', Number.isInteger(reps) && reps > 0 && text(execution.preregistrationRef),
    'repetitions must be preregistered (positive integer + preregistration reference) — post-hoc sample selection is forbidden');

  // --- verdict ---------------------------------------------------------------
  const offlineUnknowns = mode === 'offline-stub'
    && HOST_PROBE_VARIABLES.every((variable) => armIds.every((armId) => {
      const armLoad = perArmLoad[armId];
      return !armLoad || armLoad[{ model: 'modelIdentity', systemPrompt: 'systemPromptHash', provider: 'providerIdentity', plugin: 'pluginSetHash', tools: 'toolsSetHash', memory: 'memoryIdentity', hook: 'hookSetHash', session: 'sessionIdentity', workspace: 'workspaceIdentity' }[variable]] == null;
    }));
  let status;
  if (problems.length > 0) status = 'EXPERIMENT_INVALID';
  else if (mode === 'offline-stub' && offlineUnknowns) status = 'ISOLATION_VERIFIED_OFFLINE_SCOPE';
  else status = 'ISOLATION_VERIFIED';
  return {
    ok: problems.length === 0,
    status,
    design: spec.designId,
    mode,
    loadStates: state.perArm,
    problems,
    checks,
    rule: 'EXPERIMENT_INVALID excludes the study from primary effect analysis; ISOLATION_VERIFIED_OFFLINE_SCOPE proves only what an offline run can prove — host-shaped facts stay UNKNOWN and must never be cited as isolated',
  };
}
