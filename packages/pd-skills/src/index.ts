/**
 * PD 内置技能渲染器：单一源（skills/<skill>/<lang>.md）→ 各宿主交付目录。
 *
 * 模板语法（只有两种，渲染器不提供第三条路径）：
 * - `{{capability <id>}}`
 *   宿主必须提供该能力的渲染块（hosts/<id>.json 的 capabilities[lang][id]）。
 *   未提供但在 unsupported[lang] 中声明 → 渲染成显式声明段（"本宿主不支持…应改走…"）。
 *   两者都没有 → fail-closed，报出 host / skill / lang / capability。
 * - `{{host.optional.<key>}}` 可选片段（例如命令后缀），缺失渲染为空。
 *
 * 结构性约束：
 * - hosts/<id>.json 不认识 "skills" 之类的字段：未知顶层字段直接报错，因此
 *   "让某个宿主少装一个技能"在配置层没有表达方式。
 * - 渲染器的技能集合来自 skills/ 目录，对所有宿主完全相同。
 * - `--check` 额外检测交付目录里的陈旧技能目录，退场必须四份同进同退。
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';

export const GENERATED_HEADER =
  '<!-- generated by @principles/pd-skills; edit packages/pd-skills/skills/** -->';

export const SOURCE_ROOT = 'skills';
export const HOST_ROOT = 'hosts';

const HOST_FIELDS = new Set([
  '$comment',
  'id',
  'displayName',
  'frontmatter',
  'destinations',
  'optional',
  'capabilities',
  'unsupported',
]);

const CAPABILITY_TOKEN = /\{\{capability\s+([a-zA-Z0-9][a-zA-Z0-9._-]*)\s*\}\}/g;
const OPTIONAL_TOKEN = /\{\{host\.optional\.([a-zA-Z0-9][a-zA-Z0-9._-]*)\}\}/g;
const ANY_TOKEN = /\{\{[^}]*\}\}/;

/** 声明段的固定措辞。模板文字属于渲染脚手架，不属于宿主事实。 */
const DECLARATION_LABELS: Readonly<
  Record<string, { readonly reason: string; readonly alternative: string }>
> = {
  zh: { reason: '本宿主不支持：', alternative: '应改走：' },
  en: { reason: 'This host does not support: ', alternative: 'Use instead: ' },
};

export class SkillRenderError extends Error {
  readonly problems: readonly string[];

  constructor(problems: readonly string[]) {
    super(problems.join('\n'));
    this.name = 'SkillRenderError';
    this.problems = problems;
  }
}

export interface UnsupportedDeclaration {
  readonly capability: string;
  readonly reason: string;
  readonly alternative: string;
}

export interface HostConfig {
  readonly id: string;
  readonly displayName: string;
  readonly frontmatter: Readonly<Record<string, string>>;
  /** lang → 仓库相对交付目录 */
  readonly destinations: Readonly<Record<string, string>>;
  readonly optional: Readonly<Record<string, Readonly<Record<string, string>>>>;
  readonly capabilities: Readonly<Record<string, Readonly<Record<string, string>>>>;
  readonly unsupported: Readonly<Record<string, readonly UnsupportedDeclaration[]>>;
}

export interface SkillSource {
  readonly id: string;
  /** lang → 源文件绝对路径 */
  readonly bodies: Readonly<Record<string, string>>;
}

export interface RenderedFile {
  readonly host: string;
  readonly lang: string;
  readonly skill: string;
  readonly relativePath: string;
  readonly absolutePath: string;
  readonly content: string;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function readObjectOfStrings(
  value: unknown,
  where: string,
  problems: string[],
): Record<string, string> {
  if (value === undefined) return {};
  if (!isRecord(value)) {
    problems.push(`${where}: expected an object of string values`);
    return {};
  }
  const out: Record<string, string> = {};
  for (const [key, raw] of Object.entries(value)) {
    if (typeof raw !== 'string') {
      problems.push(`${where}.${key}: expected a string`);
      continue;
    }
    out[key] = raw;
  }
  return out;
}

function readNestedStringMap(
  value: unknown,
  where: string,
  problems: string[],
): Record<string, Record<string, string>> {
  if (value === undefined) return {};
  if (!isRecord(value)) {
    problems.push(`${where}: expected an object keyed by language`);
    return {};
  }
  const out: Record<string, Record<string, string>> = {};
  for (const [lang, raw] of Object.entries(value)) {
    out[lang] = readObjectOfStrings(raw, `${where}.${lang}`, problems);
  }
  return out;
}

function readUnsupported(
  value: unknown,
  where: string,
  problems: string[],
): Record<string, UnsupportedDeclaration[]> {
  if (value === undefined) return {};
  if (!isRecord(value)) {
    problems.push(`${where}: expected an object keyed by language (required, may be empty)`);
    return {};
  }
  const out: Record<string, UnsupportedDeclaration[]> = {};
  for (const [lang, raw] of Object.entries(value)) {
    if (!Array.isArray(raw)) {
      problems.push(`${where}.${lang}: expected an array (required, may be empty)`);
      continue;
    }
    const items: UnsupportedDeclaration[] = [];
    raw.forEach((entry, index) => {
      const label = `${where}.${lang}[${index}]`;
      if (!isRecord(entry)) {
        problems.push(`${label}: expected an object`);
        return;
      }
      const { capability, reason, alternative } = entry;
      if (typeof capability !== 'string' || capability.length === 0) {
        problems.push(`${label}.capability: expected a non-empty string`);
        return;
      }
      if (typeof reason !== 'string' || reason.length === 0) {
        problems.push(`${label}.reason: expected a non-empty string`);
        return;
      }
      if (typeof alternative !== 'string' || alternative.length === 0) {
        problems.push(`${label}.alternative: expected a non-empty string`);
        return;
      }
      items.push({ capability, reason, alternative });
    });
    out[lang] = items;
  }
  return out;
}

export function parseHostConfig(value: unknown, label: string): HostConfig {
  const problems: string[] = [];
  if (!isRecord(value)) {
    throw new SkillRenderError([`${label}: host config must be a JSON object`]);
  }
  for (const key of Object.keys(value)) {
    if (!HOST_FIELDS.has(key)) {
      problems.push(
        `${label}: unknown field "${key}" — host configs cannot declare skill-set overrides (H1)`,
      );
    }
  }
  const id = typeof value.id === 'string' ? value.id : '';
  const displayName = typeof value.displayName === 'string' ? value.displayName : '';
  if (!/^[a-z][a-z0-9-]*$/.test(id)) {
    problems.push(`${label}.id: expected a lowercase kebab-case identifier`);
  }
  if (displayName.length === 0) {
    problems.push(`${label}.displayName: expected a non-empty string`);
  }
  const destinations = readObjectOfStrings(value.destinations, `${label}.destinations`, problems);
  const langs = Object.keys(destinations);
  if (langs.length === 0) {
    problems.push(`${label}.destinations: at least one language destination is required`);
  }
  for (const [lang, destination] of Object.entries(destinations)) {
    if (destination.startsWith('/') || destination.includes('..')) {
      problems.push(`${label}.destinations.${lang}: must be a repository-relative path`);
    }
  }
  const optional = readNestedStringMap(value.optional, `${label}.optional`, problems);
  const capabilities = readNestedStringMap(value.capabilities, `${label}.capabilities`, problems);
  const unsupported = readUnsupported(value.unsupported, `${label}.unsupported`, problems);

  for (const lang of langs) {
    if (!Object.hasOwn(capabilities, lang)) {
      problems.push(`${label}.capabilities.${lang}: missing (required, may be empty)`);
    }
    if (!Object.hasOwn(unsupported, lang)) {
      problems.push(`${label}.unsupported.${lang}: missing (required, may be empty)`);
    }
    const declared = new Set((unsupported[lang] ?? []).map((entry) => entry.capability));
    for (const capability of Object.keys(capabilities[lang] ?? {})) {
      if (declared.has(capability)) {
        problems.push(
          `${label}: capability "${capability}" is both provided and declared unsupported for ${lang}`,
        );
      }
    }
  }
  for (const lang of Object.keys(unsupported)) {
    if (!langs.includes(lang)) {
      problems.push(`${label}.unsupported.${lang}: no destination declared for this language`);
    }
  }

  if (problems.length > 0) throw new SkillRenderError(problems);

  return {
    id,
    displayName,
    frontmatter: readObjectOfStrings(value.frontmatter, `${label}.frontmatter`, []),
    destinations,
    optional,
    capabilities,
    unsupported,
  };
}

export function loadHosts(packageRoot: string): readonly HostConfig[] {
  const hostsDir = join(packageRoot, HOST_ROOT);
  if (!existsSync(hostsDir)) {
    throw new SkillRenderError([`missing host config directory: ${hostsDir}`]);
  }
  const hosts: HostConfig[] = [];
  const problems: string[] = [];
  for (const entry of readdirSync(hostsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() && entry.name.endsWith('.json')) {
      const file = join(hostsDir, entry.name);
      let parsed: unknown;
      try {
        parsed = JSON.parse(readFileSync(file, 'utf-8'));
      } catch (error) {
        problems.push(`${file}: invalid JSON (${(error as Error).message})`);
        continue;
      }
      try {
        hosts.push(parseHostConfig(parsed, entry.name));
      } catch (error) {
        if (error instanceof SkillRenderError) problems.push(...error.problems);
        else throw error;
      }
    }
  }
  if (problems.length > 0) throw new SkillRenderError(problems);
  if (hosts.length === 0) throw new SkillRenderError(['no host configs found under hosts/']);
  const seen = new Set<string>();
  for (const host of hosts) {
    if (seen.has(host.id)) throw new SkillRenderError([`duplicate host id "${host.id}"`]);
    seen.add(host.id);
  }
  return hosts.sort((a, b) => a.id.localeCompare(b.id));
}

export function loadSkillSources(packageRoot: string): readonly SkillSource[] {
  const skillsDir = join(packageRoot, SOURCE_ROOT);
  if (!existsSync(skillsDir)) {
    throw new SkillRenderError([`missing skill source directory: ${skillsDir}`]);
  }
  const skills: SkillSource[] = [];
  for (const entry of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(skillsDir, entry.name);
    const bodies: Record<string, string> = {};
    for (const file of readdirSync(dir, { withFileTypes: true })) {
      if (!file.isFile() || !file.name.endsWith('.md')) continue;
      bodies[file.name.slice(0, -'.md'.length)] = join(dir, file.name);
    }
    if (Object.keys(bodies).length === 0) {
      throw new SkillRenderError([`skill source "${entry.name}" contains no <lang>.md files`]);
    }
    skills.push({ id: entry.name, bodies });
  }
  if (skills.length === 0) throw new SkillRenderError(['no skill sources found under skills/']);
  return skills.sort((a, b) => a.id.localeCompare(b.id));
}

interface SplitSource {
  readonly frontmatter: readonly string[];
  readonly body: string;
}

export function splitSource(text: string, label: string): SplitSource {
  const normalised = text.replace(/\r\n/g, '\n');
  const lines = normalised.split('\n');
  if (lines[0] !== '---') {
    throw new SkillRenderError([`${label}: source must start with a YAML frontmatter block`]);
  }
  const end = lines.indexOf('---', 1);
  if (end === -1) {
    throw new SkillRenderError([`${label}: unterminated frontmatter block`]);
  }
  return {
    frontmatter: lines.slice(1, end),
    body: lines
      .slice(end + 1)
      .join('\n')
      .replace(/^\n+/, '')
      .replace(/\s+$/, ''),
  };
}

function declarationBlock(
  host: HostConfig,
  lang: string,
  declaration: UnsupportedDeclaration,
): string {
  const labels = DECLARATION_LABELS[lang];
  if (!labels) {
    throw new SkillRenderError([
      `host "${host.id}" lang "${lang}": no declaration wording registered for this language — ` +
        'an unsupported capability cannot be rendered silently',
    ]);
  }
  return `${labels.reason}${declaration.reason}\n${labels.alternative}${declaration.alternative}`;
}

interface SubstituteContext {
  readonly host: HostConfig;
  readonly lang: string;
  readonly skill: string;
  readonly problems: string[];
}

function substituteBody(
  body: string,
  context: SubstituteContext,
): { body: string; referenced: Set<string> } {
  const { host, lang, skill, problems } = context;
  const referenced = new Set<string>();
  const where = `skills/${skill}/${lang}.md → ${host.id}`;
  const provided = host.capabilities[lang] ?? {};
  const declared = new Map(
    (host.unsupported[lang] ?? []).map((entry) => [entry.capability, entry]),
  );

  let out = body.replace(CAPABILITY_TOKEN, (_match, capability: string) => {
    referenced.add(capability);
    const block = provided[capability];
    if (block !== undefined) return block.replace(/\s+$/, '');
    const declaration = declared.get(capability);
    if (declaration) return declarationBlock(host, lang, declaration);
    problems.push(
      `${where}: capability "${capability}" is neither provided nor declared unsupported — ` +
        'the section cannot be silently dropped',
    );
    return '';
  });

  const optional = host.optional[lang] ?? {};
  out = out.replace(OPTIONAL_TOKEN, (_match, key: string) => optional[key] ?? '');

  const leftover = ANY_TOKEN.exec(out);
  if (leftover) {
    problems.push(`${where}: unresolved placeholder ${leftover[0]}`);
  }
  return { body: out, referenced };
}

interface RenderRequest {
  readonly sourcePath: string;
  readonly host: HostConfig;
  readonly lang: string;
  readonly skill: string;
}

export function renderSkill({
  sourcePath,
  host,
  lang,
  skill,
}: RenderRequest): { content: string; referenced: Set<string> } {
  const label = `skills/${skill}/${lang}.md`;
  const raw = readFileSync(sourcePath, 'utf-8');
  const split = splitSource(raw, label);
  const problems: string[] = [];
  const frontmatterLines: string[] = [];
  const frontmatterReferenced = substituteBody(split.frontmatter.join('\n'), {
    host,
    lang,
    skill,
    problems,
  });
  if (frontmatterReferenced.referenced.size > 0) {
    problems.push(`${label}: capability placeholders are not allowed in frontmatter`);
  }
  frontmatterLines.push(...frontmatterReferenced.body.split('\n'));
  for (const [key, value] of Object.entries(host.frontmatter)) {
    frontmatterLines.push(`${key}: ${value}`);
  }
  const substituted = substituteBody(split.body, { host, lang, skill, problems });
  if (problems.length > 0) throw new SkillRenderError(problems);

  const content =
    ['---', ...frontmatterLines, '---', '', GENERATED_HEADER, '', substituted.body, ''].join('\n');

  return { content, referenced: substituted.referenced };
}

export function renderWorkspace(
  packageRoot: string,
  repoRoot = resolve(packageRoot, '..', '..'),
): readonly RenderedFile[] {
  const hosts = loadHosts(packageRoot);
  const skills = loadSkillSources(packageRoot);
  const files: RenderedFile[] = [];
  const problems: string[] = [];
  const referencedByLang = new Map<string, Set<string>>();

  for (const host of hosts) {
    for (const [lang, destination] of Object.entries(host.destinations)) {
      for (const skill of skills) {
        const sourcePath = skill.bodies[lang];
        if (!sourcePath) {
          problems.push(
            `skill "${skill.id}" has no ${lang} source, but host "${host.id}" delivers ${lang}`,
          );
          continue;
        }
        const rendered = renderSkill({ sourcePath, host, lang, skill: skill.id });
        const refs = referencedByLang.get(lang) ?? new Set<string>();
        for (const capability of rendered.referenced) refs.add(capability);
        referencedByLang.set(lang, refs);
        const relativePath = `${destination}/${skill.id}/SKILL.md`;
        files.push({
          host: host.id,
          lang,
          skill: skill.id,
          relativePath,
          absolutePath: join(repoRoot, relativePath),
          content: rendered.content,
        });
      }
    }
  }

  for (const host of hosts) {
    for (const lang of Object.keys(host.destinations)) {
      const refs = referencedByLang.get(lang) ?? new Set<string>();
      for (const capability of Object.keys(host.capabilities[lang] ?? {})) {
        if (!refs.has(capability)) {
          problems.push(
            `host "${host.id}" provides capability "${capability}" but no ${lang} skill body references it`,
          );
        }
      }
      for (const entry of host.unsupported[lang] ?? []) {
        if (!refs.has(entry.capability)) {
          problems.push(
            `host "${host.id}" declares "${entry.capability}" unsupported but no ${lang} skill body references it`,
          );
        }
      }
    }
  }

  if (problems.length > 0) throw new SkillRenderError(problems);
  return files;
}

export function writeWorkspace(
  packageRoot: string,
  repoRoot = resolve(packageRoot, '..', '..'),
): readonly RenderedFile[] {
  const files = renderWorkspace(packageRoot, repoRoot);
  for (const file of files) {
    mkdirSync(dirname(file.absolutePath), { recursive: true });
    writeFileSync(file.absolutePath, file.content, 'utf-8');
  }
  return files;
}

/** 返回所有偏差；空数组表示交付目录与单一源完全一致。 */
export function checkWorkspace(
  packageRoot: string,
  repoRoot = resolve(packageRoot, '..', '..'),
): readonly string[] {
  const files = renderWorkspace(packageRoot, repoRoot);
  const problems: string[] = [];
  const expectedSkills = new Set(files.map((file) => file.skill));
  const destinations = new Map<string, Set<string>>();

  for (const file of files) {
    if (!existsSync(file.absolutePath)) {
      problems.push(`${file.relativePath}: missing (run "pd-skills render")`);
      continue;
    }
    const actual = readFileSync(file.absolutePath, 'utf-8');
    if (actual !== file.content) {
      problems.push(`${file.relativePath}: out of date (run "pd-skills render")`);
    }
  }

  for (const file of files) {
    const destination = file.relativePath
      .slice(0, -(file.skill.length + '/SKILL.md'.length))
      .replace(/\/$/, '');
    const set = destinations.get(destination) ?? new Set<string>();
    set.add(file.skill);
    destinations.set(destination, set);
  }
  for (const destination of destinations.keys()) {
    const dir = join(repoRoot, destination);
    if (!existsSync(dir)) continue;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      if (!expectedSkills.has(entry.name)) {
        problems.push(
          `${destination}/${entry.name}: stale skill directory — not produced by any source skill`,
        );
      }
    }
  }

  return problems.sort();
}

export function packageRootOf(moduleUrl: string): string {
  return resolve(dirname(new URL(moduleUrl).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
}

export function isInside(root: string, candidate: string): boolean {
  const normalisedRoot = resolve(root) + sep;
  return resolve(candidate).startsWith(normalisedRoot);
}
