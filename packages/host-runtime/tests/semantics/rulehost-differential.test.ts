/**
 * PRI-1208 Stage 0 — frozen RuleHost decision corpus.
 *
 * This file freezes the OBSERVABLE decision tuple of the single live runtime
 * path (`createProductionRuleHostGate`, reached through
 * `createProductionHostRuntime(...).dispatch`). It intentionally runs no
 * legacy `RuleHost` oracle: the legacy path has no production wiring, and the
 * audit baseline (`docs/reports/PD_RULEHOST_SEMANTIC_AUDIT_20261112.md`,
 * `38ef598`) already established that the live path is the only verdict
 * producer.
 *
 * Differential, not characterization: `fixtures/rulehost-semantics/baseline-
 * 68401244.json` was GENERATED by running this exact corpus on `68401244bf`
 * (`RULEHOST_CORPUS_EMIT=<path>`), before any convergence change. Every legacy
 * key of the head tuple must equal that frozen baseline. `evaluationFaults` is
 * the one deliberate new plane added by PRI-1208; its expected value is
 * declared per case in `cases.json` and the baseline must be empty for it.
 *
 * Provenance has two layers, and they prove different things:
 *   1. SOURCE identity (enforced here): the fixture records the sha256 of the
 *      decision-producing source files AT `68401244bf`; the provenance test
 *      re-reads those blobs from git. The branch under test cannot satisfy
 *      this by editing the fixture alone.
 *   2. OUTPUT origin (recorded, not replayed in CI): the fixture was emitted
 *      by a real run in a worktree whose HEAD was `68401244bf`. The command,
 *      worktree HEAD and artifact sha256 are recorded in the PR. CI does not
 *      rebuild the old tree; it only checks the source digests.
 *
 * `reason` text is deliberately not compared (wording is not semantics).
 *
 * Regenerating the oracle:
 *   RULEHOST_CORPUS_EMIT=<absolute path> npx vitest run \
 *     packages/host-runtime/tests/semantics/rulehost-differential.test.ts
 * Run it in a worktree based on `68401244bf`, never on a branch that contains
 * the change under test.
 *
 * Adjacent frozen evidence lives in dedicated tests and is referenced instead
 * of duplicated here:
 *   - resource bounds / 32-rule limit / 64KB / 3s deadline:
 *     `tests/production-host-runtime.test.ts`
 *   - duplicate target_ref, tampered digest:
 *     `tests/production-rulehost-gate-digest.test.ts`
 *   - v2 suspension when history is unavailable:
 *     `tests/production-rulehost-gate-v2-isolation.test.ts`
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as yaml from 'js-yaml';
import { afterAll, afterEach, describe, expect, it } from 'vitest';
import { SqliteActivationStateStore, SqliteConnection, getDefaultPdConfig } from '@principles/core/runtime';
import { createProductionHostRuntime } from '../../src/index.js';

type RuleMode = 'live' | 'shadow';

interface RuleSpec {
  mode: RuleMode;
  behavior: string;
  ruleId: string;
  principleId?: string;
  enforcement?: 'safety_isolated';
}

interface ExpectedTuple {
  decision: 'allow' | 'deny';
  matched: boolean | null;
  ruleId: string | null;
  principleId: string | null;
  ruleDecision: string | null;
  warningCodes: string[];
  evaluationDecisions: string[];
  hasCorrectionProposal: boolean;
  /** Console reads this directly; it must be frozen too. */
  evaluatedLiveRules: number | null;
  /**
   * PRI-1208 new plane. Format: `kind:mode:activationId:artifactId:ruleId:
   * reasonCode`. Diagnostic lineage, never a decision input.
   */
  evaluationFaults: string[];
}

interface CorpusCase {
  id: string;
  toolName: string;
  params: Record<string, unknown>;
  rules: RuleSpec[];
  expectedFaults?: string[];
}

interface CorpusFile {
  corpusVersion: number;
  cases: CorpusCase[];
}

interface BaselineFile {
  baseline: string;
  /**
   * sha256 of the decision-producing source files AT THE BASELINE COMMIT.
   * The provenance test re-reads them from git, so the digest cannot be
   * satisfied by the branch under test — it proves the fixture points at a
   * real, independently readable tree.
   */
  sourceDigests: Record<string, string>;
  corpusVersion: number;
  cases: Record<string, ExpectedTuple>;
}

interface GateResult {
  decision: 'allow' | 'deny';
  reason?: string;
  warnings?: string[];
  metadata?: Readonly<Record<string, unknown>>;
}

const FIXTURE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'rulehost-semantics');
const CORPUS = JSON.parse(fs.readFileSync(path.join(FIXTURE_DIR, 'cases.json'), 'utf8')) as CorpusFile;
const BASELINE_PATH = path.join(FIXTURE_DIR, 'baseline-68401244.json');
const EMIT_PATH = process.env['RULEHOST_CORPUS_EMIT'];
const EMITTED: Record<string, ExpectedTuple> = {};

const BASELINE: BaselineFile | null = EMIT_PATH === undefined
  ? JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8')) as BaselineFile
  : (fs.existsSync(BASELINE_PATH) ? JSON.parse(fs.readFileSync(BASELINE_PATH, 'utf8')) as BaselineFile : null);

const tempDirs: string[] = [];

function tempWorkspace(): string {
  const workspaceDir = fs.mkdtempSync(path.join(os.tmpdir(), 'pd-rulehost-corpus-'));
  tempDirs.push(workspaceDir);
  fs.mkdirSync(path.join(workspaceDir, '.pd'), { recursive: true });
  fs.writeFileSync(path.join(workspaceDir, '.pd', 'config.yaml'), yaml.dump(getDefaultPdConfig()), 'utf8');
  return workspaceDir;
}

afterEach(() => {
  for (const dir of tempDirs.splice(0)) {
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 3, retryDelay: 50 });
  }
});

afterAll(() => {
  if (EMIT_PATH === undefined) return;
  fs.writeFileSync(EMIT_PATH, `${JSON.stringify({
    source: 'Generated by running packages/host-runtime/tests/semantics/rulehost-differential.test.ts with RULEHOST_CORPUS_EMIT on the listed baseline commit.',
    baseline: '68401244bf5e0924fa257dae45d8874944bb7acb',
    corpusVersion: CORPUS.corpusVersion,
    cases: EMITTED,
  }, null, 2)}\n`, 'utf8');
}, 30_000);

function behaviorBody(behavior: string): string {
  switch (behavior) {
    case 'block-on-risk-path':
      return `
  if (typeof input.action.normalizedPath === 'string' && input.action.normalizedPath.indexOf('/etc/') === 0) {
    return { decision: 'block', matched: true, reason: 'risk path' };
  }
  return { decision: 'allow', matched: false, reason: 'not a risk path' };`;
    case 'block-empty-reason':
      return `\n  return { decision: 'block', matched: true, reason: '' };`;
    case 'allow':
      return `\n  return { decision: 'allow', matched: false, reason: 'no opinion' };`;
    case 'auto-correct':
      return `
  return {
    decision: 'auto_correct',
    matched: true,
    reason: 'rewrite unsafe content',
    correctionProposal: {
      proposedParams: { file_path: input.action.normalizedPath, content: 'safe' },
      correctedFields: [{ field: 'content', original: 'unsafe', proposed: 'safe', reason: 'unsafe content' }],
      applicationMode: 'live',
      confidence: 0.9,
      ruleId: 'R_AC',
      principleId: 'P_AC',
      notifyAgent: true
    }
  };`;
    case 'require-approval':
      return `\n  return { decision: 'requireApproval', matched: true, reason: 'owner approval required' };`;
    case 'invalid-output':
      return `\n  return { decision: 'nope' };`;
    case 'block-on-synthetic-target':
      return `
  if (typeof input.action.normalizedPath === 'string' && input.action.normalizedPath.indexOf('<tool:') === 0) {
    return { decision: 'block', matched: true, reason: 'synthetic target' };
  }
  return { decision: 'allow', matched: false, reason: 'has a real path' };`;
    case 'block-on-risk-flag':
      return `
  if (input.workspace.isRiskPath === true) {
    return { decision: 'block', matched: true, reason: 'risk flag' };
  }
  return { decision: 'allow', matched: false, reason: 'not a risk flag' };`;
    case 'block-on-line-changes':
      return `
  if (input.derived.estimatedLineChanges > 0) {
    return { decision: 'block', matched: true, reason: 'line changes visible' };
  }
  return { decision: 'allow', matched: false, reason: 'no line changes' };`;
    case 'block-on-tier':
      return `
  if (input.evolution.epTier === 1) {
    return { decision: 'block', matched: true, reason: 'tier one' };
  }
  return { decision: 'allow', matched: false, reason: 'not tier one' };`;
    case 'block-on-bash-risk':
      return `
  if (input.derived.bashRisk === 'dangerous') {
    return { decision: 'block', matched: true, reason: 'dangerous bash risk' };
  }
  return { decision: 'allow', matched: false, reason: 'bash risk is not dangerous' };`;
    case 'block-on-bash-path':
      return `
  if (input.action.normalizedPath === '/etc/important.conf') {
    return { decision: 'block', matched: true, reason: 'bash mutation target extracted' };
  }
  return { decision: 'allow', matched: false, reason: 'no mutation target' };`;
    default:
      throw new Error(`unknown corpus behavior: ${behavior}`);
  }
}

function ruleCode(rule: RuleSpec): string {
  // A syntactically broken RuleCode is the corpus form of an unhealthy
  // implementation (the gate's compile catch produces the fault).
  if (rule.behavior === 'broken-compile') {
    return 'function evaluate(input) {';
  }
  return `function evaluate(input) {${behaviorBody(rule.behavior)}
}
var meta = { name: ${JSON.stringify(rule.ruleId)}, version: '1', ruleId: ${JSON.stringify(rule.ruleId)}, coversCondition: 'all' };`;
}

async function seedRule(workspaceDir: string, rule: RuleSpec, suffix: string): Promise<void> {
  const connection = new SqliteConnection(workspaceDir);
  try {
    const now = new Date().toISOString();
    connection.getDb().prepare(`
      INSERT INTO pi_artifacts (artifact_id, artifact_kind, source_task_id, source_principle_id, source_rule_id, lineage_artifact_ids, validation_status, content_json, created_at, updated_at)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    `).run(
      `art-${suffix}`, 'rule', `task-${suffix}`, rule.principleId ?? 'P_CORPUS', rule.ruleId, '[]', 'validated',
      JSON.stringify({
        principleId: rule.principleId ?? 'P_CORPUS',
        ruleId: rule.ruleId,
        implementationCode: ruleCode(rule),
      }),
      now, now,
    );
    await new SqliteActivationStateStore(connection).recordActivation({
      activationId: `act-${suffix}`,
      idempotencyKey: `${suffix}::${rule.mode}`,
      artifactId: `art-${suffix}`,
      channel: 'code_tool_hook',
      action: rule.mode === 'live' ? 'code_tool_hook_live_activate' : 'code_tool_hook_shadow_activate',
      targetRef: `impl://${rule.ruleId}`,
      activatedAt: now,
      deactivatedAt: null,
    });
    if (rule.enforcement === 'safety_isolated') {
      // recordActivation already created the eligible control row; the safety
      // store transitions it (never a second row).
      connection.getDb().prepare(`
        UPDATE activation_control_states
        SET enforcement = 'safety_isolated', isolation_decision_id = NULL, version = version + 1, updated_at = ?
        WHERE activation_id = ?
      `).run(now, `act-${suffix}`);
    }
  } finally {
    connection.close();
  }
}

function gateEvent(workspaceDir: string, toolName: string, params: Record<string, unknown>) {
  return {
    kind: 'before_tool_call' as const,
    context: { workspaceDir, sessionId: 'session-corpus', toolName },
    rawPayload: { toolInput: { toolName, params } },
    source: 'test:rulehost-corpus',
  };
}

function warningCode(warning: string): string {
  const head = warning.split('; nextAction=')[0] ?? warning;
  const colon = head.indexOf(':');
  return (colon >= 0 ? head.slice(0, colon) : head).trim();
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

const REPO_ROOT = path.resolve(FIXTURE_DIR, '../../../../..');

/**
 * Read a file exactly as it exists at the baseline commit. The CI job that
 * runs this suite (`test-shared-runtime`) checks out with `fetch-depth: 0`
 * (see .github/workflows/ci.yml); a shallow clone fails loudly here rather
 * than silently accepting an unverifiable oracle.
 */
function sha256AtBaseline(file: string, commit: string): string {
  let content: Buffer;
  try {
    content = execFileSync('git', ['cat-file', '-p', `${commit}:${file}`], {
      cwd: REPO_ROOT,
      maxBuffer: 10 * 1024 * 1024,
    });
  } catch (error) {
    throw new Error(
      `Cannot read ${commit}:${file} for baseline provenance. `
      + 'Run in a full clone (CI uses fetch-depth: 0) or fetch the base commit. '
      + String(error),
    );
  }
  return createHash('sha256').update(content).digest('hex');
}

function faultTuple(entry: unknown): string | null {
  if (!isRecord(entry)) return null;
  const kind = typeof entry['kind'] === 'string' ? entry['kind'] : 'unknown';
  const mode = typeof entry['mode'] === 'string' ? entry['mode'] : 'na';
  const activationId = typeof entry['activationId'] === 'string' ? entry['activationId'] : 'unknown';
  const artifactId = typeof entry['artifactId'] === 'string' ? entry['artifactId'] : 'unknown';
  const ruleId = typeof entry['ruleId'] === 'string' ? entry['ruleId'] : 'unknown';
  const reason = typeof entry['reason'] === 'string' ? entry['reason'] : '';
  const reasonCode = reason.split(':')[0]?.trim() ?? '';
  return `${kind}:${mode}:${activationId}:${artifactId}:${ruleId}:${reasonCode}`;
}

export function decisionTuple(result: GateResult): ExpectedTuple {
  const metadata = result.metadata ?? {};
  const rawEvaluations = Array.isArray(metadata['evaluations']) ? metadata['evaluations'] : [];
  const evaluationDecisions = rawEvaluations
    .filter(isRecord)
    .map((entry) => {
      const mode = typeof entry['activationMode'] === 'string' ? entry['activationMode'] : 'live';
      const decision = typeof entry['decision'] === 'string' ? entry['decision'] : 'unknown';
      return `${mode}:${decision}`;
    })
    .sort();
  const rawFaults = Array.isArray(metadata['evaluationFaults']) ? metadata['evaluationFaults'] : [];
  return {
    decision: result.decision,
    matched: typeof metadata['matched'] === 'boolean' ? metadata['matched'] : null,
    ruleId: typeof metadata['ruleId'] === 'string' ? metadata['ruleId'] : null,
    principleId: typeof metadata['principleId'] === 'string' ? metadata['principleId'] : null,
    ruleDecision: typeof metadata['ruleDecision'] === 'string' ? metadata['ruleDecision'] : null,
    // `[RuleHost] ...` lines are forwarded internal log text, not host contract
    // warnings; the tuple freezes the latter only (wording is not semantics).
    warningCodes: (result.warnings ?? []).map(warningCode).filter((code) => !code.startsWith('[RuleHost]')).sort(),
    evaluationDecisions,
    hasCorrectionProposal: Object.hasOwn(metadata, 'correctionProposal') && metadata['correctionProposal'] !== undefined,
    evaluatedLiveRules: typeof metadata['evaluatedLiveRules'] === 'number' ? metadata['evaluatedLiveRules'] : null,
    evaluationFaults: rawFaults.map(faultTuple).filter((value): value is string => value !== null).sort(),
  };
}

export function compareDecisionTuples(actual: ExpectedTuple, expected: ExpectedTuple): string[] {
  const diffs: string[] = [];
  for (const key of [
    'decision', 'matched', 'ruleId', 'principleId', 'ruleDecision', 'hasCorrectionProposal', 'evaluatedLiveRules',
  ] as const) {
    if (actual[key] !== expected[key]) diffs.push(`${key}: expected ${JSON.stringify(expected[key])}, got ${JSON.stringify(actual[key])}`);
  }
  for (const key of ['warningCodes', 'evaluationDecisions', 'evaluationFaults'] as const) {
    if (actual[key].join('|') !== expected[key].join('|')) {
      diffs.push(`${key}: expected ${JSON.stringify(expected[key])}, got ${JSON.stringify(actual[key])}`);
    }
  }
  return diffs;
}

async function runCorpusCase(testCase: CorpusCase): Promise<GateResult> {
  const workspaceDir = tempWorkspace();
  // Create the governance store even for the zero-rule case: a missing DB is a
  // different degradation (`activation_db_not_found`) than "armed but empty".
  const bootstrap = new SqliteConnection(workspaceDir);
  bootstrap.getDb();
  bootstrap.close();
  for (const [index, rule] of testCase.rules.entries()) {
    await seedRule(workspaceDir, rule, `${testCase.id}-${index}`);
  }
  const runtime = createProductionHostRuntime({
    hostKind: 'openclaw',
    afterToolCall: async (event) => ({ decision: 'observe', source: event.source }),
  });
  return runtime.dispatch(gateEvent(workspaceDir, testCase.toolName, testCase.params));
}

describe('RuleHost frozen semantic corpus (PRI-1208 stage 0)', () => {
  it('loads a non-empty, versioned corpus and a generated baseline', () => {
    if (EMIT_PATH !== undefined) return;
    expect(CORPUS.corpusVersion).toBe(1);
    expect(CORPUS.cases.length).toBeGreaterThanOrEqual(10);
    const ids = CORPUS.cases.map((entry) => entry.id);
    expect(new Set(ids).size).toBe(ids.length);
    expect(BASELINE?.baseline).toBe('68401244bf5e0924fa257dae45d8874944bb7acb');
    expect(BASELINE?.corpusVersion).toBe(CORPUS.corpusVersion);
    // Every corpus input must have a real baseline row: a case added without
    // a baseline run would silently lose its differential oracle.
    expect(Object.keys(BASELINE?.cases ?? {}).sort()).toEqual([...ids].sort());
  });

  it('provenance: the recorded digests equal the 68401244bf blobs', () => {
    if (EMIT_PATH !== undefined) return;
    if (!BASELINE) throw new Error('baseline-68401244.json is missing');
    const entries = Object.entries(BASELINE.sourceDigests);
    // Every decision-producing file must be covered: a missing entry is a
    // silently unverifiable oracle.
    expect(entries.map(([file]) => file).sort()).toEqual([
      'packages/host-runtime/src/index.ts',
      'packages/host-runtime/src/production-rulehost-gate.ts',
      'packages/host-runtime/src/rule-implementation-runtime.ts',
      'packages/principles-core/src/runtime/internalization/bash-risk.ts',
      'packages/principles-core/src/runtime/internalization/rule-host-contracts.ts',
      'packages/principles-core/src/runtime/internalization/rule-host-input-builder.ts',
      'packages/principles-core/src/runtime/risk/risk-calculator-policy.ts',
    ]);
    for (const [file, digest] of entries) {
      expect(sha256AtBaseline(file, BASELINE.baseline), `digest for ${file}`).toBe(digest);
    }
  });

  for (const testCase of CORPUS.cases) {
    it(`matches the 68401244bf baseline for ${testCase.id}`, async () => {
      const actual = decisionTuple(await runCorpusCase(testCase));
      if (EMIT_PATH !== undefined) {
        EMITTED[testCase.id] = actual;
        return;
      }
      const baselineRow = BASELINE?.cases[testCase.id];
      if (!baselineRow) throw new Error(`baseline-68401244.json is missing ${testCase.id}`);
      // The baseline predates the structured fault plane, so it must be empty
      // there. That is what makes `expectedFaults` a declared NEW behavior
      // rather than a tautologically copied expectation.
      expect(baselineRow.evaluationFaults).toEqual([]);
      const expected: ExpectedTuple = { ...baselineRow, evaluationFaults: testCase.expectedFaults ?? [] };
      expect(compareDecisionTuples(actual, expected)).toEqual([]);
    });
  }

  it('sensitivity: the comparator rejects flipped decision, matched, ruleId, live count and fault', async () => {
    if (EMIT_PATH !== undefined) return;
    const sample = CORPUS.cases.find((entry) => entry.id === 'live-allow');
    if (!sample) throw new Error('corpus is missing the live-allow sensitivity sample');
    const baselineRow = BASELINE?.cases[sample.id];
    if (!baselineRow) throw new Error('baseline is missing the live-allow sample');
    const expected = { ...baselineRow, evaluationFaults: sample.expectedFaults ?? [] };
    const actual = decisionTuple(await runCorpusCase(sample));
    expect(compareDecisionTuples(actual, expected)).toEqual([]);
    expect(compareDecisionTuples(actual, { ...expected, decision: 'deny' })).toContain(
      'decision: expected "deny", got "allow"',
    );
    expect(compareDecisionTuples(actual, { ...expected, matched: true })).toContain(
      'matched: expected true, got false',
    );
    expect(compareDecisionTuples(actual, { ...expected, ruleId: 'R_FAKE' })).toContain(
      'ruleId: expected "R_FAKE", got null',
    );
    expect(compareDecisionTuples(actual, { ...expected, evaluatedLiveRules: 99 })).toContain(
      'evaluatedLiveRules: expected 99, got 1',
    );
    expect(compareDecisionTuples(actual, {
      ...expected,
      evaluationFaults: ['unhealthy:live:act-x:art-x:R_X:implementation_unhealthy'],
    })).toContain(
      'evaluationFaults: expected ["unhealthy:live:act-x:art-x:R_X:implementation_unhealthy"], got []',
    );
  });

  it('freezes the epTier policy: absent enrichment=0, OpenClaw enrichment=1', async () => {
    const workspaceDir = tempWorkspace();
    await seedRule(workspaceDir, {
      mode: 'live', behavior: 'block-on-tier', ruleId: 'R_TIER', principleId: 'P_TIER',
    }, 'tier');

    const defaultRuntime = createProductionHostRuntime({
      hostKind: 'openclaw',
      afterToolCall: async (event) => ({ decision: 'observe', source: event.source }),
    });
    await expect(defaultRuntime.dispatch(gateEvent(workspaceDir, 'write_file', { file_path: '/tmp/tier.txt', content: 'x' })))
      .resolves.toMatchObject({ decision: 'allow' });

    const enrichedRuntime = createProductionHostRuntime({
      hostKind: 'openclaw',
      ruleInputEnrichmentProvider: () => ({ epTier: 1, bashRisk: 'normal' }),
      afterToolCall: async (event) => ({ decision: 'observe', source: event.source }),
    });
    await expect(enrichedRuntime.dispatch(gateEvent(workspaceDir, 'write_file', { file_path: '/tmp/tier.txt', content: 'x' })))
      .resolves.toMatchObject({ decision: 'deny' });
  });
});
